/**
 * 高效内存分配工具
 *
 * 功能概述:
 *   	提供对齐到 2 的幂次的 TypedArray 内存分配方法
 *   	通过将缓冲区大小对齐到 2 的幂, 可以:
 *   		- 利用内存对齐优化 CPU 缓存命中率
 *   		- 减少内存碎片
 *   		- 某些平台下对齐的 ArrayBuffer 有更好的 SIMD 性能
 *
 * 算法原理 (bitsNextPow2):
 *   	- 使用位运算将任意正整数向上取整到最近的 2 的幂次
 *   	- 通过逐步将最高有效位右移并做或运算, 将所有低位填充为 1, 最后加 1 得到下一个 2 的幂
 *
 * 例:
 * 		- v = 5 (二进制 101)
 *     		v -= 1  // 4 (100)
 *     		v |= v >>> 1  // 110
 *     		v |= v >>> 2  // 111
 *     		v |= v >>> 4  // 111
 *     		v |= v >>> 8  // 111
 *     		v |= v >>> 16  // 111
 *     		v + 1  // 1000 = 8
 */

/**
 * 将正整数向上取整到最近的 2 的幂次
 *
 * 		输入:
 * 			0 ~ 2^31 (受 32 位整数限制) 的整数 v
 * 		输出:
 * 			大于等于 v 的最小 2 的幂
 *
 * 位运算解析:
 *   	- +(_v === 0)  // 处理边界情况, 当 v = 0 时变为 1
 *   	- _v -= 1  // 处理 v 本身就是 2 的幂的情况(避免翻倍)
 *   	- 逐级右移或  // 将最高位以下的所有位都置 1
 *   	- 最后 + 1   // 得到只有最高位为 1 的数(即 2 的幂)
 */
function bitsNextPow2(v: number): number {
	let _v: number = v
	/**
	 *  若 v = 0, 则 _v = 1, 避免后续结果为 0
	 */
	_v += +(_v === 0) //
	/**
	 * 减 1: 使得已是 2 的幂的数不会翻倍 (如 8 → 7 → 8)
	 */
	_v -= 1
	/**
	 * 将最高位复制到下一位
	 */
	_v |= _v >>> 1
	/**
	 * 将高 2 位复制到接下来 2 位
	 */
	_v |= _v >>> 2
	/**
	 * 将高 4 位复制到接下来 4 位
	 */
	_v |= _v >>> 4
	/**
	 * 将高 8 位复制到接下来 8 位
	 */
	_v |= _v >>> 8
	/**
	 * 将高 16 位复制到接下来 16 位
	 */
	_v |= _v >>> 16
	/**
	 * 所有低位都是 1, 加 1 进位得到 2 的幂
	 */
	return _v + 1
}

/**
 * 分配一个长度为 n 的 Uint32Array, 底层 ArrayBuffer 大小对齐到 2 的幂
 *
 * 		输入:
 * 			n: 需要的 Uint32 元素个数
 * 		输出:
 * 			长度为 n 的 Uint32Array 视图
 *
 * 内存布局:
 *   	- ArrayBuffer 大小 = bitsNextPow2(4 * n) 字节
 *   	- Uint32Array 视图从 offset = 0 开始, 长度为 n
 *   	- 多出的字节作为对齐填充(不使用)
 *
 * 案例:
 *   	- mallocUint32(3)
 *   		// 3 * 4 = 12 字节 → bitsNextPow2(12) = 16 字节 ArrayBuffer
 *   		// 返回 Uint32Array(3), 使用前 12 字节
 *
 *   	- mallocUint32(100)
 *   		// 100 * 4 = 400 字节 → bitsNextPow2(400) = 512 字节 ArrayBuffer
 *   		// 返回 Uint32Array(100), 使用前 400 字节
 */
export function mallocUint32(n: number): Uint32Array {
	return new Uint32Array(new ArrayBuffer(bitsNextPow2(4 * n)), 0, n)
}
